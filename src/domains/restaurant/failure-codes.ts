export function isRestaurantFailureCode(value: unknown): value is RestaurantFailureCode {
  return typeof value === "string" && Object.hasOwn(RESTAURANT_FAILURE_CLASSIFICATION, value);
}

/** Unrecognized external errors fail as an execution invariant, never as business exhaustion. */
export function restaurantFailureCode(value: unknown, fallback: RestaurantFailureCode): RestaurantFailureCode {
  if (value === undefined) return fallback;
  return isRestaurantFailureCode(value) ? value : "AGENT_EXECUTION_FAILED";
}
