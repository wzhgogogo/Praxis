function pending(...annotationFocus: string[]): DecisionEvalPendingExpectation {
  return { annotationStatus: PENDING_HUMAN_LABEL, annotationFocus };
}

function fixtureFactRefsFor(candidateIds: readonly string[], includeBrand = false): string[] {
  return candidateIds.flatMap((candidateId) => {
    const refs = STANDARD_CANDIDATE_FACT_SUFFIXES.map(
      (suffix) => `${candidateId}.${suffix}`,
    );
    if (includeBrand) refs.push(`${candidateId}.brand`);
    return refs;
  });
}

function outletIdentityFactRefsFor(candidateIds: readonly string[]): string[] {
  return candidateIds.flatMap((candidateId) => [
    `${candidateId}.outlet-name`,
    `${candidateId}.area`,
    `${candidateId}.brand`,
  ]);
}

function allergyConfirmationDisclosuresFor(candidateIds: readonly string[]) {
  return candidateIds.map((candidateId) => ({
    candidateId,
    type: "ALLERGY_CONFIRMATION_REQUIRED" as const,
    factRef: `${candidateId}.attributes`,
  }));
}

