import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {writeFileSync} from 'node:fs';
import {assessRestaurantConditions} from '../../../src/domains/restaurant/condition-states.js';
import {restaurantCurrentFactEvidence,restaurantPresentationEvidenceIds} from '../../../src/domains/restaurant/read-assessment.js';
const source='769766455c38c369fa61bad56112de45230dfc68:.eval-artifacts/phase3b/g6-development-live/d4-d6-safety-only/runs/D4/execution.result.json';
const bytes=execFileSync('git',['show',source],{maxBuffer:8_000_000});
const sha=createHash('sha256').update(bytes).digest('hex');
assert.equal(sha,'d74f901dfa54b5a42e9bfd8823da291b23ecb16c08dd132602e9a11f229eaa18');
const artifact=JSON.parse(bytes.toString());
const state=artifact.execution.finalSnapshot.domainState;
const candidateId='praxis:restaurant:c446fe0b901cca8ffb43b42e';
const now=state.presentedResults.presentedAt;
const current=restaurantCurrentFactEvidence(state,candidateId);
const before=state.presentedResults.conditionStates[candidateId][0];
const after=assessRestaurantConditions(state.intentDraft,current,now)[0]!;
const report={source,sha,now,candidateId,before,after,eligible:Boolean(restaurantPresentationEvidenceIds(state,candidateId,now))};
if(process.argv[2])writeFileSync(process.argv[2],JSON.stringify(report,null,2)+'\n');
assert.equal(report.eligible,true);
assert.equal(before.status,'NOT_CHECKED');
assert.equal(after.status,'MET');
assert.ok(after.sources.some(q=>q.quote==='揚げ物メニュー：串カツ、アジフライなど'&&q.sourceUrl==='https://www.1bangai.org/daioh'));
assert.deepEqual(after.sources,before.sources,'retain the original Japanese source quote byte for byte');
console.log(JSON.stringify(report,null,2));
