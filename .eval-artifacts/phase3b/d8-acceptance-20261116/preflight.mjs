import assert from 'node:assert/strict';
import { readFile, writeFile, unlink } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const root=dirname(fileURLToPath(import.meta.url));
const json=async name=>JSON.parse(await readFile(join(root,name),'utf8'));
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const config=await json('d8/config.json'), specs=await json('d8/specs.json');
const git=(...args)=>execFileSync('git',['--no-optional-locks','-C',config.sourceRoot,...args],{encoding:'utf8'}).trim();
assert.equal(git('rev-parse','HEAD'),config.sourceSHA);
assert.equal(git('status','--porcelain'),'');
assert.equal(git('diff',config.sourceCodeSHA,config.sourceSHA,'--','src','web-skills'),'');
const {frozenHoldoutReadRules}=await import(pathToFileURL(join(config.sourceRoot,'src/eval/restaurant/agent-loop/g6/holdout-runner.ts')));
assert.equal(specs.length,1);
assert.equal(specs[0].witness.date,'2026-11-18');
assert.equal(specs[0].witness.partySize,2);
assert.equal(specs[0].witness.time,'20:30');
assert.deepEqual(specs[0].oracle.reviewedReadRules,await frozenHoldoutReadRules());
const ledger=await json('d8/active-budget.json');
assert.deepEqual(ledger.limits,{fullLive:1,evaluationPublicGET:8,realModelCalls:55,environmentReruns:0});
assert.equal(ledger.cumulative.fullLive,0);
const marker=join(root,'d8','.writable-check');
await writeFile(marker,'local only',{flag:'wx'});await unlink(marker);
const files=['run-smoke.ts','preflight.mjs','protection.py','privacy.mjs','plan.md','routing-before.json','protected-before.json','d8/config.json','d8/specs.json','d8/budget-before.json'];
await writeFile(join(root,'configuration-hashes.json'),JSON.stringify({files:Object.fromEntries(await Promise.all(files.map(async file=>[file,hash(await readFile(join(root,file)))]))),envFileSHA256:hash(await readFile(config.environmentFile))},null,2)+'\n',{flag:'wx'});
await writeFile(join(root,'offline-preflight.json'),JSON.stringify({passed:true,sourceSHA:config.sourceSHA,notBeforeUTC:config.notBeforeUTC,externalCalls:0,plannedLive:1},null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({passed:true,notBeforeUTC:config.notBeforeUTC,externalCalls:0}));
