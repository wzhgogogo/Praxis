import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';

const entry = fileURLToPath(new URL('./praxis-worktree.mjs', import.meta.url));
test('real worktree entry excludes history before checkout, restores exact batches, and preserves another tree and shared config', () => {
  const temporary = mkdtempSync(join(tmpdir(), 'praxis-worktree-contract-'));
  const source = join(temporary, 'source'), existing = join(temporary, 'existing'), fresh = join(temporary, 'fresh');
  mkdirSync(source);
  const git = (root, ...args) => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8', stdio: ['ignore','pipe','pipe'] }).trim();
  const run = (...args) => spawnSync(process.execPath, [entry, ...args], { cwd: source, encoding: 'utf8' });
  try {
    git(source, 'init', '-qb', 'main'); git(source, 'config', 'user.email', 'fixture@example.invalid'); git(source, 'config', 'user.name', 'Fixture');
    git(source, 'config', 'extensions.worktreeConfig', 'true');
    mkdirSync(join(source, '.eval-artifacts/p1-f-20261011'), { recursive: true });
    mkdirSync(join(source, '.eval-artifacts/history with spaces'), { recursive: true });
    writeFileSync(join(source, 'code.txt'), 'source code\n');
    writeFileSync(join(source, '.eval-artifacts/p1-f-20261011/variants.yaml'), 'verified required fixture\n');
    writeFileSync(join(source, '.eval-artifacts/history with spaces/recording.json'), '{"immutable":true}\n');
    writeFileSync(join(source, '.eval-artifacts/history with spaces/large.json'), 'x'.repeat(8192));
    git(source, 'add', '.'); git(source, 'commit', '-qm', 'contract fixture');
    git(source, 'worktree', 'add', '--detach', existing, 'HEAD');
    git(existing, 'config', '--worktree', 'core.sparseCheckout', 'false');
    writeFileSync(join(existing, 'uncommitted.txt'), 'must remain\n');
    const remoteBaseline = git(source, 'rev-parse', 'HEAD');
    git(source, 'update-ref', 'refs/remotes/origin/main', remoteBaseline);
    writeFileSync(join(source, 'local-main-entry.txt'), 'local main includes the unpublished entry\n');
    git(source, 'add', 'local-main-entry.txt'); git(source, 'commit', '-qm', 'unpublished local main entry');
    const localMain = git(source, 'rev-parse', 'main');
    const sharedConfig = readFileSync(join(source, '.git/config'));
    const otherConfig = readFileSync(join(source, '.git/worktrees/existing/config.worktree'));
    const otherStatus = git(existing, 'status', '--porcelain');
    const created = run('create', fresh, '--detach');
    assert.equal(created.status, 0, created.stderr);
    const receipt = JSON.parse(created.stdout);
    assert.equal(receipt.sha, localMain, 'default follows local main while origin/main is stale');
    assert.equal(readFileSync(join(fresh, 'local-main-entry.txt'), 'utf8'), 'local main includes the unpublished entry\n');
    const historical = join(temporary, 'historical');
    const explicit = run('create', historical, '--detach', '--ref', 'origin/main');
    assert.equal(explicit.status, 0, explicit.stderr);
    assert.equal(JSON.parse(explicit.stdout).sha, remoteBaseline);
    assert.equal(existsSync(join(historical, 'local-main-entry.txt')), false);
    assert.equal(receipt.evalBeforeCheckout.files, 0);
    assert.equal(receipt.evalAfterCheckout.files, 1);
    assert.equal(receipt.omittedEvalFiles, 2);
    assert.equal(readFileSync(join(fresh, 'code.txt'), 'utf8'), 'source code\n');
    assert.equal(existsSync(join(fresh, '.eval-artifacts/history with spaces')), false);
    assert.equal(git(fresh, 'status', '--porcelain'), '');
    assert.notEqual(run('create', existing, '--detach', '--ref', 'HEAD').status, 0);
    assert.notEqual(run('create', join(temporary, 'invalid'), '--detach', '--ref', 'absent-ref').status, 0);
    assert.equal(existsSync(join(temporary, 'invalid')), false);
    assert.notEqual(run('restore', existing, 'history with spaces').status, 0, 'existing worktrees have no entry-owned state');
    assert.notEqual(run('restore', fresh, '../history').status, 0);
    writeFileSync(join(fresh, 'code.txt'), 'uncommitted change');
    assert.notEqual(run('restore', fresh, 'history with spaces').status, 0);
    assert.equal(readFileSync(join(fresh, 'code.txt'), 'utf8'), 'uncommitted change');
    writeFileSync(join(fresh, 'code.txt'), 'source code\n');
    const restored = run('restore', fresh, 'history with spaces');
    assert.equal(restored.status, 0, restored.stderr);
    assert.equal(JSON.parse(restored.stdout).batchFiles, 2);
    assert.equal(readFileSync(join(fresh, '.eval-artifacts/history with spaces/recording.json'), 'utf8'), '{"immutable":true}\n');
    assert.equal(git(fresh, 'status', '--porcelain'), '');
    assert.deepEqual(readFileSync(join(source, '.git/config')), sharedConfig);
    assert.deepEqual(readFileSync(join(source, '.git/worktrees/existing/config.worktree')), otherConfig);
    assert.equal(git(existing, 'status', '--porcelain'), otherStatus);
    assert.equal(readFileSync(join(existing, 'uncommitted.txt'), 'utf8'), 'must remain\n');
  } finally { rmSync(temporary, { recursive: true, force: true }); }
});
